function generateReferenceCorrelationMatrix(): number[][] {
  const n = 30;
  const mat: number[][] = Array.from({ length: n }, () => Array(n).fill(1.0));
  
  // Cluster boundary indices
  const clusterRanges = [
    [0, 6],   // Optics & Networking (7)
    [7, 11],  // Electrical & Power Mgmt (5)
    [12, 16], // Semiconductors (5)
    [17, 22], // Power Generation (6)
    [23, 29]  // Datacenter REITs & Thermal (7)
  ];
  
  for (let i = 0; i < n; i++) {
    for (let j = 0; j < n; j++) {
      if (i === j) {
        mat[i][j] = 1.00;
        continue;
      }
      
      const sameCluster = clusterRanges.some(([start, end]) => i >= start && i <= end && j >= start && j <= end);
      
      // Deterministic synthetic baseline matching real statistics
      const baseCorr = sameCluster ? 0.49 : 0.37;
      const variation = (((i * 17 + j * 31) % 25) - 12) / 100;
      let val = Math.min(0.85, Math.max(0.12, baseCorr + variation));
      
      // Specific pairs from FRD
      if ((i === 23 && j === 25) || (i === 25 && j === 23)) val = 0.68; // DLR & EQIX
      if ((i === 18 && j === 20) || (i === 20 && j === 18)) val = 0.58; // CEG & NEE
      if ((i === 5 && j === 6) || (i === 6 && j === 5)) val = 0.62;   // GLW & LITE
      if ((i === 11 && j === 26) || (i === 26 && j === 11)) val = 0.52; // VRT & FIX
      
      mat[i][j] = Number(val.toFixed(2));
      mat[j][i] = mat[i][j];
    }
  }
  return mat;
}
